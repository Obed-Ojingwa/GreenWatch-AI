"""DEV ONLY: run one synthetic investigation end to end WITHOUT calling Meta.

Uses the same fake Meta client as the test suite and computer-generated imagery, so you can see the UI
and API working before Gate 0 passes. Everything it creates is titled "[SYNTHETIC DEV DATA]".

NEVER use its output for the demo video, the public sample, or the submission: the hackathon requires
real Meta model responses. It refuses to run when ENVIRONMENT=production.

    cd backend && python ../scripts/dev_fake_run.py            # uses backend/.env or the environment
"""
from __future__ import annotations

import sys
from pathlib import Path

BACKEND = Path(__file__).resolve().parents[1] / "backend"
sys.path.insert(0, str(BACKEND))

from app.core.config import get_settings  # noqa: E402


def main() -> None:
    s = get_settings()
    if s.environment.lower() == "production":
        sys.exit("Refusing to create synthetic data in production.")

    from app.db.session import SessionLocal, init_dev_db
    from app.services.agent import execute_run
    from app.services.storage import get_storage
    from tests.helpers import FakeMeta, make_investigation, make_pair, new_run

    init_dev_db()
    db, storage = SessionLocal(), get_storage()
    earlier, newer = make_pair(1)
    inv = make_investigation(db, storage, earlier, newer, categories=("buildings", "vegetation"))
    inv.title = "[SYNTHETIC DEV DATA] Example site"
    inv.objective = "Synthetic images generated by scripts/dev_fake_run.py. Not real imagery; not a real result."
    db.commit()
    run = new_run(db, inv, categories=("buildings", "vegetation"))
    execute_run(db, run.id, FakeMeta(), storage)
    db.refresh(run)
    print(f"investigation: {inv.id}\nrun:           {run.id}\nstatus:        {run.status}")
    if run.error:
        print(f"error:         {run.error}")


if __name__ == "__main__":
    main()
